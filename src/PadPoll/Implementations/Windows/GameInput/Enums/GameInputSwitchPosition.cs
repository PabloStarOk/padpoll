namespace PadPoll.Implementations.Windows.GameInput.Enums;

/// <summary>
/// Specifies the position of a switch on a device.
/// </summary>
internal enum GameInputSwitchPosition
{
    /// <summary>The switch is in the center position.</summary>
    Center = 0,

    /// <summary>The switch is in the up position.</summary>
    Up = 1,

    /// <summary>The switch is in the up-right position.</summary>
    UpRight = 2,

    /// <summary>The switch is in the right position.</summary>
    Right = 3,

    /// <summary>The switch is in the down-right position.</summary>
    DownRight = 4,

    /// <summary>The switch is in the down position.</summary>
    Down = 5,

    /// <summary>The switch is in the down-left position.</summary>
    DownLeft = 6,

    /// <summary>The switch is in the left position.</summary>
    Left = 7,

    /// <summary>The switch is in the up-left position.</summary>
    UpLeft = 8,
}